// Builds the provider logo sprite from the vendored LobeHub marks:
//   node scripts/provider-sprite.mjs          write sprite.svg + sprite-ids.ts
//   node scripts/provider-sprite.mjs --check  fail when they are out of date
//
// One cached file instead of every logo inlined into the JS bundle and into
// each page; <ProviderLogo> points at a symbol with <use>.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { optimize } from 'svgo';

const dir = new URL(
    '../src/components/provider-mark/',
    import.meta.url,
).pathname;
const marksDir = join(dir, 'marks');
const check = process.argv.includes('--check');

const slugs = readdirSync(marksDir)
    .filter((file) => file.endsWith('.svg'))
    .map((file) => file.slice(0, -4))
    .sort();

const symbols = slugs.map((slug) => {
    const source = readFileSync(join(marksDir, `${slug}.svg`), 'utf8');
    const { data } = optimize(source, {
        multipass: true,
        plugins: [
            'preset-default',
            'removeTitle',
            'removeDimensions',
            { name: 'removeAttrs', params: { attrs: ['svg:style'] } },
            { name: 'prefixIds', params: { prefix: `pm-${slug}` } },
        ],
    });

    const root = data.match(/^<svg([^>]*)>([\s\S]*)<\/svg>$/);
    if (!root) {
        throw new Error(`${slug}.svg: no root <svg> after optimising`);
    }
    const [, attributes, body] = root;
    const viewBox = attributes.match(/viewBox="([^"]+)"/)?.[1];
    if (!viewBox) {
        throw new Error(`${slug}.svg: viewBox is required`);
    }
    // fill and fill-rule live on a <g>: presentation attributes on <symbol>
    // are not inherited the same way in every engine.
    const paint = [
        ...attributes.matchAll(/\s(fill|fill-rule|clip-rule)="([^"]+)"/g),
    ]
        .map(([, name, value]) => ` ${name}="${value}"`)
        .join('');

    return `<symbol id="${slug}" viewBox="${viewBox}"><g${paint}>${body}</g></symbol>`;
});

const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join('')}</svg>\n`;
const ids = `// Generated by scripts/provider-sprite.mjs from marks/*.svg; do not edit.\nexport const SPRITE_IDS: ReadonlySet<string> = new Set([\n${slugs.map((slug) => `    '${slug}',`).join('\n')}\n]);\n`;

const outputs = [
    [join(dir, 'sprite.svg'), sprite],
    [join(dir, 'sprite-ids.ts'), ids],
];

if (check) {
    const stale = outputs.filter(([path, content]) => {
        try {
            return readFileSync(path, 'utf8') !== content;
        } catch {
            return true;
        }
    });
    if (stale.length > 0) {
        console.error(
            `Out of date: ${stale.map(([path]) => path).join(', ')}. Run npm run sprite`,
        );
        process.exit(1);
    }
} else {
    for (const [path, content] of outputs) {
        writeFileSync(path, content);
    }
    console.log(`${slugs.length} marks, sprite ${sprite.length} bytes`);
}
